#!/usr/bin/env bash
# Build the PokeTactics Android shell App (apps/android, docs/73) and publish it to the
# always-on preview so phones can download it from http://<dev-machine-IP>:8820/app.
#
#   tools/android/build.sh                 # build + publish to the preview's app dir
#   tools/android/build.sh --no-publish    # build only (APK path printed at the end)
#   SHELL_URL=http://10.37.30.198:8899/play tools/android/build.sh   # other default address
#
# Inputs (all outside the repository):
#   ~/.config/poketactics-preview/env           PREVIEW_CERT_DIR / PREVIEW_APP_DIR / ports (tools/preview/install.sh)
#   $PREVIEW_CERT_DIR/ca.crt, server.crt        preview CA (bundled as a trust anchor) and the machine's IPs
#   ~/.config/poketactics-android/              fixed signing key (created on first run, never committed)
# Toolchain: JDK 17 + Android SDK in the user's home (tools/android/setup_sdk.sh).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
app=$repo/apps/android
publish=1
[ "${1:-}" = "--no-publish" ] && publish=0

if [ -f "${POKETACTICS_PREVIEW_ENV:-$HOME/.config/poketactics-preview/env}" ]; then
  . "${POKETACTICS_PREVIEW_ENV:-$HOME/.config/poketactics-preview/env}"
fi
data=$HOME/.local/share/poketactics-preview
PREVIEW_PORT=${PREVIEW_PORT:-8820}
PREVIEW_TLS_PORT=${PREVIEW_TLS_PORT-8821}
PREVIEW_CERT_DIR=${PREVIEW_CERT_DIR:-$data/certs}
PREVIEW_APP_DIR=${PREVIEW_APP_DIR:-$data/app}
key_dir=${POKETACTICS_ANDROID_KEYS:-$HOME/.config/poketactics-android}

# ---------------------------------------------------------------- toolchain
export ANDROID_HOME=${ANDROID_HOME:-$HOME/.local/share/android-sdk}
if [ -z "${JAVA_HOME:-}" ] || ! "$JAVA_HOME/bin/java" -version 2>&1 | grep -qE 'version "(1[7-9]|2[0-9])'; then
  JAVA_HOME=$(ls -d "$HOME"/.local/share/jdk/jdk-17* 2>/dev/null | sort -V | tail -1 || true)
fi
if [ -z "$JAVA_HOME" ] || [ ! -d "$ANDROID_HOME/platforms/android-36" ]; then
  echo "JDK 17 / Android SDK missing: run tools/android/setup_sdk.sh" >&2
  exit 1
fi
export JAVA_HOME
# This network reaches services.gradle.org / Maven over IPv6 while Java's IPv4 default times out.
export GRADLE_OPTS="${GRADLE_OPTS:-} -Djava.net.preferIPv6Addresses=true"

# ---------------------------------------------------------------- addresses + trust
# The preview machine's IPs: the server certificate's IP names (LAN + VPN), else hostname -I.
hosts=""
if [ -s "$PREVIEW_CERT_DIR/server.crt" ]; then
  hosts=$(openssl x509 -in "$PREVIEW_CERT_DIR/server.crt" -noout -ext subjectAltName 2>/dev/null \
          | grep -oE 'IP Address:[0-9.]+' | cut -d: -f2 | tr '\n' ' ')
fi
[ -n "$hosts" ] || hosts="$(hostname -I | tr ' ' '\n' | grep -E '^[0-9]+(\.[0-9]+){3}$' | tr '\n' ' ')127.0.0.1"
primary=${PREVIEW_PRIMARY_IP:-$(hostname -I | awk '{print $1}')}
ca=""
[ -s "$PREVIEW_CERT_DIR/ca.crt" ] && ca=$PREVIEW_CERT_DIR/ca.crt
if [ -n "${SHELL_URL:-}" ]; then url=$SHELL_URL
elif [ -n "$ca" ] && [ -n "$PREVIEW_TLS_PORT" ]; then url="https://$primary:$PREVIEW_TLS_PORT/play"
else url="http://$primary:$PREVIEW_PORT/play"; fi

gen=$app/app/src/generated/res
rm -rf "$gen"
mkdir -p "$gen/xml" "$gen/raw"
{
  echo '<?xml version="1.0" encoding="utf-8"?>'
  echo '<!-- Generated by tools/android/build.sh (docs/73); not committed. -->'
  echo '<network-security-config>'
  echo '    <!-- Everywhere else: https with the system CAs only. -->'
  echo '    <base-config cleartextTrafficPermitted="false">'
  echo '        <trust-anchors><certificates src="system" /></trust-anchors>'
  echo '    </base-config>'
  echo '    <!-- The preview machine: its https port with the bundled preview CA (name-constrained'
  echo '         to these addresses), and plain http for branch servers started without TLS. -->'
  echo '    <domain-config cleartextTrafficPermitted="true">'
  for h in $hosts localhost; do echo "        <domain includeSubdomains=\"false\">$h</domain>"; done
  echo '        <trust-anchors>'
  [ -n "$ca" ] && echo '            <certificates src="@raw/preview_ca" />'
  echo '            <certificates src="system" />'
  echo '        </trust-anchors>'
  echo '    </domain-config>'
  echo '</network-security-config>'
} > "$gen/xml/network_security_config.xml"
if [ -n "$ca" ]; then
  openssl x509 -in "$ca" -outform PEM -out "$gen/raw/preview_ca.crt"   # public certificate only
else
  rmdir "$gen/raw"
  echo "note: no preview CA at $PREVIEW_CERT_DIR/ca.crt; https to the preview will be refused" >&2
fi

# ---------------------------------------------------------------- signing key (outside the repo)
props=$key_dir/keystore.properties
if [ ! -s "$props" ]; then
  mkdir -p "$key_dir"
  chmod 700 "$key_dir"
  pass=$(openssl rand -hex 24)
  "$JAVA_HOME/bin/keytool" -genkeypair -noprompt -keystore "$key_dir/shell.jks" -storetype PKCS12 \
    -storepass "$pass" -keypass "$pass" -alias poketactics-shell -keyalg RSA -keysize 3072 -validity 10950 \
    -dname "CN=PokeTactics Preview Shell, O=PokeTactics (non-commercial preview)" >/dev/null
  umask 077
  printf 'storeFile=%s\nstorePassword=%s\nkeyAlias=poketactics-shell\nkeyPassword=%s\n' \
    "$key_dir/shell.jks" "$pass" "$pass" > "$props"
  chmod 600 "$props" "$key_dir/shell.jks"
  echo "created signing key $key_dir/shell.jks (back it up: a new key cannot update installed Apps)"
fi

# ---------------------------------------------------------------- build
count=$(git -C "$repo" rev-list --count HEAD)
commit=$(git -C "$repo" rev-parse --short HEAD)
dirty=$(git -C "$repo" status --porcelain -- apps/android tools/acceptance/play_mobile.js | head -1)
version_name="1.0.$count${dirty:+-dev}"
host_list=$(echo $hosts | tr ' ' ',')
(cd "$app" && ./gradlew --no-daemon -q assembleDebug \
  -Ppoketactics.defaultUrl="$url" -Ppoketactics.hosts="$host_list" \
  -Ppoketactics.versionCode="$count" -Ppoketactics.versionName="$version_name" \
  -Ppoketactics.keystoreProperties="$props")
apk=$app/app/build/outputs/apk/debug/app-debug.apk
build_tools=$ANDROID_HOME/build-tools/36.0.0
"$build_tools/apksigner" verify "$apk"
cert_sha=$("$build_tools/apksigner" verify --print-certs "$apk" | sed -n 's/.*certificate SHA-256 digest: //p' | head -1)
sha=$(sha256sum "$apk" | awk '{print $1}')
echo "built $apk  version $version_name ($count)  default $url"
echo "trusted preview hosts: $host_list${ca:+  (bundled CA $ca)}"

[ "$publish" = 1 ] || exit 0
mkdir -p "$PREVIEW_APP_DIR"
cp "$apk" "$PREVIEW_APP_DIR/.PokeTactics.apk.tmp"
mv "$PREVIEW_APP_DIR/.PokeTactics.apk.tmp" "$PREVIEW_APP_DIR/PokeTactics.apk"
cat > "$PREVIEW_APP_DIR/PokeTactics.json" <<JSON
{"versionName": "$version_name", "versionCode": $count, "commit": "$commit", "defaultUrl": "$url",
 "builtAt": "$(date '+%Y-%m-%d %H:%M %Z')", "sha256": "$sha", "certSha256": "$cert_sha"}
JSON
echo "published http://$primary:$PREVIEW_PORT/app  ->  http://$primary:$PREVIEW_PORT/app/PokeTactics.apk"
