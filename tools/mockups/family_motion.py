# Coordinates are normalized to the occupied source-art bounding box, in the
# source art's intrinsic left-facing orientation: x increases left-to-right and
# y increases top-to-bottom.  A renderer that mirrors the art must also mirror x.
@dataclass(frozen=True)
class Profile:
    archetype: str
    stage: int
    attack_note: str
    cast_note: str
    emitter: tuple[float, float]


def _rows(species, archetype, attack_note, cast_note):
    return {
        sid: Profile(archetype, index, attack_note, cast_note, tuple(emitter))
        for index, (sid, emitter) in enumerate(species)
    }


