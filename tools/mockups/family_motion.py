def _mixed(a, b, amount):
    return round(a + (b-a) * amount)


def sample_action(sid, kind, state, p):
    """Sample one whole-body track as ``(dx, dy, sx%, sy%, angle, dissolve)``.

    ``p`` is the normalized phase progress within ``state``.  Input is clamped
    only by explicit validation below; no clock, battle state, or RNG is read.
    """
    profile = _PROFILES.get(sid)
    if profile is None:
        raise ValueError(f"family motion/{sid}: unsupported species")
    if type(kind) is not str or kind not in KINDS:
        raise ValueError("kind must be 'attack' or 'cast'")
    if type(state) is not str or state not in ACTION_STATES:
        raise ValueError("state must be windup, strike, or recover")
    if type(p) not in (int, float) or isinstance(p, bool) or not math.isfinite(p) or not 0 <= p <= 1:
        raise ValueError("p must be a finite number in [0, 1]")
    keys = _ACTIONS[profile.archetype][kind][state]
    position = p * (len(keys)-1)
    left = min(len(keys)-1, max(0, math.floor(position)))
    right = min(len(keys)-1, left+1)
    amount = position-left
    track = tuple(_mixed(keys[left][index], keys[right][index], amount)
                  for index in range(6))
    # Evolutionary stage scales readable amplitude, not timing.  It is derived
    # from the authored row position, never a per-call random seed.
    factor = .78 + .11 * profile.stage
    dx, dy, sx, sy, angle, dissolve = track
    return (round(dx*factor), round(dy*factor),
            round(100+(sx-100)*factor), round(100+(sy-100)*factor),
            round(angle*factor), dissolve)


def action_track(sid, kind):
    """Return a tuple of sampled keys suitable for motion's integer validator."""
    profile = _PROFILES.get(sid)
    if profile is None:
        raise ValueError(f"family motion/{sid}: unsupported species")
    if type(kind) is not str or kind not in KINDS:
        raise ValueError("kind must be 'attack' or 'cast'")
    return tuple(sample_action(sid, kind, state, index/(count-1))
                 for state, count in (("windup", 5), ("strike", 4), ("recover", 3))
                 for index in range(count))


