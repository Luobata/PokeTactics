"""Hand-authored whole-body action tracks for family battle forms.

The module is deliberately deterministic and presentation-only.  It does not
read battle state, derive values from species IDs at random, or promise limb
animation: the source cel is transformed as one body through anticipation,
release and recovery.
"""

